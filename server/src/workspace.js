const iso = (value) => new Date(value).toISOString();
const isAdmin = (user) => user.role === 'admin';
export function publicUser(row) {
  return {
    id: row.id,
    name: row.name,
    email: row.email,
    role: isAdmin(row) ? 'admin' : 'member',
    status: row.banned ? 'suspended' : 'active',
    emailVerified: Boolean(row.emailVerified),
    createdAt: iso(row.createdAt),
  };
}
function holdReasonFromEvents(events, status) {
  if (status !== 'on_hold' || !Array.isArray(events)) return '';
  return (
    [...events]
      .reverse()
      .find((event) => event.status === 'on_hold' && typeof event.holdReason === 'string')
      ?.holdReason || ''
  );
}
function mapPublicShipment(row) {
  const events = (Array.isArray(row.events) ? row.events : []).map((event) => ({
    ...event,
    holdReason: typeof event.holdReason === 'string' ? event.holdReason : '',
    photo:
      typeof event.photo === 'string' &&
      /^data:image\/(jpeg|png|webp);base64,/.test(event.photo) &&
      event.photo.length <= 400_000
        ? event.photo
        : '',
  }));
  return {
    id: row.id,
    trackingNumber: row.tracking_number,
    userId: row.owner_id || null,
    recipientLabel: row.recipient_label,
    originCity: row.origin_city,
    originRegion: row.origin_region || '',
    originPostalCode: row.origin_postal_code,
    destinationCity: row.destination_city,
    destinationRegion: row.destination_region || '',
    destinationPostalCode: row.destination_postal_code,
    service: row.service,
    weight: row.weight === null || row.weight === undefined ? '' : String(Number(row.weight)),
    shipDate: row.ship_date_text || String(row.ship_date).slice(0, 10),
    estimatedDelivery:
      row.estimated_delivery_text || (row.estimated_delivery ? String(row.estimated_delivery).slice(0, 10) : ''),
    status: row.status,
    currentLocation: row.current_location,
    holdReason: holdReasonFromEvents(events, row.status),
    publicNote: row.public_note || '',
    internalNote: row.internal_note || '',
    isPublic: Boolean(row.is_public),
    archivedAt: row.archived_at ? iso(row.archived_at) : null,
    autoProgressEnabled: Boolean(row.auto_progress_enabled),
    autoProgressIntervalMinutes: Math.min(
      1440,
      Math.max(1, Number(row.auto_progress_interval_minutes) || 5),
    ),
    autoProgressNextAt: row.auto_progress_next_at ? iso(row.auto_progress_next_at) : '',
    events,
    createdBy: row.created_by,
    createdAt: iso(row.created_at),
    updatedAt: iso(row.updated_at),
  };
}
const autoProgressStages = [
  'label_created',
  'picked_up',
  'in_transit',
  'out_for_delivery',
  'delivered',
];
const AUTO_PROGRESS_NOTE =
  'Automatic update generated by this application — not a carrier scan.';

/** Compute due automatic stage updates for a stored row; null when unchanged. */
function progressedShipment(row, now = new Date()) {
  const shipment = mapPublicShipment(row);
  if (!shipment.autoProgressEnabled || shipment.archivedAt) return null;
  const index = autoProgressStages.indexOf(shipment.status);
  if (index < 0 || index >= autoProgressStages.length - 1) {
    return { ...shipment, autoProgressEnabled: false, autoProgressNextAt: '' };
  }
  const intervalMs = shipment.autoProgressIntervalMinutes * 60_000;
  let dueAt = shipment.autoProgressNextAt
    ? new Date(shipment.autoProgressNextAt).getTime()
    : Number.NaN;
  if (!Number.isFinite(dueAt)) {
    return {
      ...shipment,
      autoProgressNextAt: new Date(now.getTime() + intervalMs).toISOString(),
    };
  }
  if (dueAt > now.getTime()) return null;
  const events = [...shipment.events];
  let status = shipment.status;
  let currentLocation = shipment.currentLocation;
  let steps = 0;
  while (dueAt <= now.getTime() && steps < 20) {
    const next = autoProgressStages[autoProgressStages.indexOf(status) + 1];
    if (!next) break;
    const location =
      next === 'out_for_delivery' || next === 'delivered'
        ? `${shipment.destinationCity}, ${shipment.destinationRegion}`
        : `${shipment.originCity}, ${shipment.originRegion}`;
    events.push({
      id: randomUUID(),
      status: next,
      location,
      note: AUTO_PROGRESS_NOTE,
      holdReason: '',
      photo: '',
      at: new Date(dueAt).toISOString(),
    });
    status = next;
    currentLocation = location;
    steps += 1;
    if (next === 'delivered') break;
    dueAt += intervalMs;
  }
  if (!steps) return null;
  const delivered = status === 'delivered';
  return {
    ...shipment,
    status,
    currentLocation,
    holdReason: '',
    events: events.slice(-100),
    autoProgressEnabled: !delivered,
    autoProgressNextAt: delivered ? '' : new Date(dueAt).toISOString(),
  };
}

async function persistAutoProgress(queryable, shipment) {
  await queryable.query(
    'UPDATE fedexr_public_shipments SET status = $1, current_location = $2, events = $3::jsonb, auto_progress_enabled = $4, auto_progress_next_at = $5, updated_at = now() WHERE id = $6',
    [
      shipment.status,
      shipment.currentLocation,
      JSON.stringify(shipment.events),
      shipment.autoProgressEnabled,
      shipment.autoProgressNextAt || null,
      shipment.id,
    ],
  );
}

function generatedTrackingNumber(service) {
  const length = service === 'ground' ? 15 : 12;
  let number = String(randomInt(1, 10));
  for (let index = 1; index < length; index += 1) number += String(randomInt(0, 10));
  return number;
}
export async function findPublicShipment(pool, trackingNumber) {
  const entered = String(trackingNumber || '').trim().toUpperCase().replace(/\s+/g, ' ');
  const compact = entered.replace(/[\s-]+/g, '');
  const normalized =
    /^\d{12}$/.test(compact) || /^\d{15}$/.test(compact) ? compact : entered;
  assert(normalized.length <= 40, 'Tracking number is too long.');
  if (!normalized) return null;
  const result = await pool.query(
    'SELECT *, ship_date::text AS ship_date_text, estimated_delivery::text AS estimated_delivery_text FROM fedexr_public_shipments WHERE tracking_number = $1 AND is_public = TRUE AND archived_at IS NULL LIMIT 1',
    [normalized],
  );
  if (!result.rows[0]) return null;
  const progressed = progressedShipment(result.rows[0]);
  if (progressed) await persistAutoProgress(pool, progressed);
  const shipment = progressed || mapPublicShipment(result.rows[0]);
  // The unauthenticated response must not expose workspace account identifiers, internal notes,
  // or the automatic-progression schedule (automatic events are labeled in the timeline itself).
  return {
    ...shipment,
    userId: null,
    createdBy: 'this site',
    internalNote: '',
    autoProgressEnabled: false,
    autoProgressNextAt: '',
  };
}
export function requireAdmin(actor) {
  assert(isAdmin(actor), 'Management access is required.', 403);
}
export async function currentActor(pool, authentication, headers) {
  const session = await authentication.api.getSession({ headers });
  assert(session?.user?.id, 'Sign in to your workspace.', 401);
  const result = await pool.query(
    'SELECT id, name, email, role, banned, "emailVerified", "createdAt" FROM fedexr_auth_user WHERE id = $1',
    [session.user.id],
  );
  const user = result.rows[0];
  assert(
    user && !user.banned && user.emailVerified,
    'This workspace session is no longer active.',
    401,
  );
  return user;
}
